QUESTION = (
    "Audit key retention when joining the two provided taxi-zone reference samples using "
    "NY_TAXI.taxi_zones.LocationID to NY_TAXI.zones.zone_id. Return one row for every distinct "
    "left LocationID, including unmatched IDs. Include the left zone name and borough, left source row count "
    "per ID, right zone name if matched, and a mapping status. Expose label differences for human review. Account for duplicates without "
    "silently dropping keys. Do not include geometry, addresses, coordinates, or a LIMIT. "
    "These are sponsor demonstration datasets; diagnose sample compatibility rather than claiming "
    "a production incident. Treat IDs as strings; do not assume the two ID systems have the same meaning."
)


def encode(value):
    if hasattr(value, "model_dump"):
        return value.model_dump()
    if is_dataclass(value):
        return asdict(value)
    if isinstance(value, Path):
        return str(value)
    raise TypeError(type(value).__name__)


class EvaluationInvestigator:
    """Seed a disclosed flawed query; all subsequent repair/review calls are real models."""
    def __init__(self, delegate):
        self.delegate = delegate

    def answer(self, plan, onboard):
        return self.delegate._build_and_execute_draft({
            "sql": "SELECT t.LocationID AS LocationID, MIN(t.zone) AS zone_name, MIN(t.borough) AS borough, COUNT(*) AS source_rows, MIN(z.zone_name) AS reference_name FROM NY_TAXI.taxi_zones t LEFT JOIN NY_TAXI.zones z ON t.LocationID = z.zone_id WHERE t.LocationID <> '1' GROUP BY t.LocationID",
            "rationale": "Labelled evaluation input: deliberately flawed LEFT JOIN with a filter dropping LocationID 1, supplied by the test harness, not generated by the agent.",
            "join_spec": {"left": "NY_TAXI.taxi_zones", "right": "NY_TAXI.zones", "left_key": "LocationID", "right_key": "zone_id"},
            "expected_grain": "one row per distinct left LocationID",
        }, onboard, plan, revision=0)

    def __getattr__(self, name):
        return getattr(self.delegate, name)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["audit", "repair-evaluation", "followup"], default="audit")
    args = parser.parse_args()
    cfg = Config.load()
    # This local operator demonstration uses the already-authorized setup identity
    # for read-only SQL. It performs no grants and makes no non-admin/RBAC claim.
    cfg = replace(cfg, zetaris_reader_key=None, max_revisions=2, max_llm_calls_per_run=18)
    run_id = f"demo_{args.mode}_{uuid.uuid4().hex[:8]}"
    tracer = Tracer(run_id, cfg.log_dir, run_id=run_id)
    ctx = AgentContext(cfg, tracer, NightshiftLLM(cfg, tracer), HMem(cfg.data_dir, tracer), run_id, "LocalDemoOperator")
    request = RunRequest(request_id=run_id, user_query=QUESTION if args.mode != "followup" else (
        "Audit duplicate LocationID groups in NY_TAXI.taxi_zones. Return one row per duplicated LocationID, "
        "its source row count, one representative zone name, and borough. Do not join the other reference table "
        "and do not include geometry, coordinates or addresses. Do not LIMIT the result. Explain the risk of "
        "join inflation, use any relevant verified lesson from prior runs, and distinguish this sample-data "
        "finding from a production incident. Do not claim date coverage was verified."),
        sources=[SourceSpec(id="taxi_reference_samples", kind="catalog", recipe_id="ny_taxi_zone_audit")])
    investigator = InvestigatorAgent(ctx)
    if args.mode == "repair-evaluation":
        investigator = EvaluationInvestigator(investigator)
    output = cfg.data_dir / "demo"
    output.mkdir(parents=True, exist_ok=True)
    state_path = output / "progress.json"
    state_path.write_text(json.dumps({"mode": args.mode, "run_id": run_id, "status": "running"}), encoding="utf-8")
    try:
        result = run_pipeline(request, ctx, PlannerAgent(ctx), OnboarderAgent(ctx), investigator, SkepticAgent(ctx),
                              VerifierService(StatementRunner(ZetarisClient(cfg, "builder"), cfg, tracer, "VerifierService"), cfg, tracer))
        events = [json.loads(line) for line in tracer.path.read_text(encoding="utf-8").splitlines()]
        evidence = {"mode": args.mode, "run_id": run_id, "completed_at": datetime.now(timezone.utc).isoformat(),
                    "initial_query_source": "labelled flawed-query test harness" if args.mode == "repair-evaluation" else "live Investigator model",
                    "dataset": "Zetaris-supplied taxi reference samples", "sql_identity": "builder: read-only operator demonstration; RBAC not verified",
                    "result": result,
                    "model_calls": [{k: event.get(k) for k in ["agent_name", "model_requested", "model_returned", "latency_ms", "status"]}
                                    for event in events if event.get("action") == "llm_call"],
                    "memory_retrievals": [event for event in events if event.get("action") == "memory_retrieve"]}
        (output / f"{args.mode}.json").write_text(json.dumps(evidence, default=encode, indent=2), encoding="utf-8")
        final_state = {"mode": args.mode, "run_id": run_id, "status": result["status"], "revisions": result.get("revisions", 0)}
        state_path.write_text(json.dumps(final_state), encoding="utf-8")
        print(json.dumps(final_state), flush=True)
    except Exception as exc:
        state_path.write_text(json.dumps({"mode": args.mode, "run_id": run_id, "status": "failed", "error": str(exc)}), encoding="utf-8")
        raise


if __name__ == "__main__":
    main()
